#!/bin/bash
# One-time setup on the Pi for first contact from a phone (ADR-0025, REQ-ONB-004). Run as root:
#
#   sudo bash infra/deploy/rpi/install-enroll-access.sh
#
# It mirrors install-update-access.sh and creates:
# - the user `mia-enroll`: locked password. sshd runs a forced command through the user's shell with `-c`, so the
#   shell is /bin/sh; the only thing the user can run is `sudo /opt/mia/bin/mia-enroll`;
# - /etc/sudoers.d/mia-enroll: that user may run that one file as root with no arguments (the empty "" in the rule),
#   checked with visudo -cf before it is put in place;
# - a small AuthorizedKeysCommand helper (root-owned, mode 755) that echoes the key the client offers (`%t %k`) with
#   the options restrict,command="sudo /opt/mia/bin/mia-enroll" for any ed25519 or ECDSA key and nothing else. SSH
#   itself does not authorize anything here: the server-signed grant that mia-enroll verifies does. Without a valid
#   grant the command changes nothing;
# - /etc/ssh/sshd_config.d/mia-enroll.conf: one `Match User mia-enroll` block; every other line is indented under it
#   so no other user is affected. The block adds no general shell, tty or forwarding.
#
# The image must also carry /opt/mia/bin/mia-enroll and mia-update-pair, /etc/mia/allowed_signers (the server's
# grant-signer key) and the SSH host keys; the host keys must not be regenerated on first boot (ADR-0025).
# The MIA_* variables let tests/unit/infra/test_enroll_access.py run it in a temporary directory.
set -euo pipefail

ENROLL_USER="${MIA_ENROLL_USER:-mia-enroll}"
SUDOERS_FILE="${MIA_ENROLL_SUDOERS_FILE:-/etc/sudoers.d/mia-enroll}"
SSHD_DROPIN="${MIA_ENROLL_SSHD_DROPIN:-/etc/ssh/sshd_config.d/mia-enroll.conf}"
KEYS_CMD="${MIA_ENROLL_KEYS_CMD:-/usr/local/sbin/mia-enroll-authkeys}"
TOOL="${MIA_ENROLL_TOOL:-/opt/mia/bin/mia-enroll}"

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

if ! id "$ENROLL_USER" >/dev/null 2>&1; then
    useradd -r -m -s /bin/sh "$ENROLL_USER"
fi
passwd -l "$ENROLL_USER" >/dev/null 2>&1 || true

# env_reset for the tool, like the one-command rule of install-update-access.sh: sudo drops the caller's environment, so
# the SSH user cannot set the MIA_* test overrides of mia-enroll.
{
    printf 'Defaults!%s env_reset\n' "$TOOL"
    printf '%s ALL=(root) NOPASSWD: %s ""\n' "$ENROLL_USER" "$TOOL"
} > "$work/sudoers"
visudo -cf "$work/sudoers"
install -m 440 "$work/sudoers" "$SUDOERS_FILE"

# The helper reads only sshd's %t (key type) and %k (base64 key), checks both and prints one authorized_keys line.
cat > "$work/authkeys" <<HELPER
#!/bin/sh
# Generated by install-enroll-access.sh (ADR-0025). Usage from sshd: mia-enroll-authkeys %t %k
case "\$1" in
    ssh-ed25519|ecdsa-sha2-nistp256|ecdsa-sha2-nistp384|ecdsa-sha2-nistp521) ;;
    *) exit 0 ;;
esac
case "\$2" in
    ""|*[!A-Za-z0-9+/=]*) exit 0 ;;
esac
printf 'restrict,command="sudo $TOOL",no-pty,no-port-forwarding,no-agent-forwarding,no-X11-forwarding,no-user-rc %s %s\n' "\$1" "\$2"
HELPER
mkdir -p "$(dirname "$KEYS_CMD")"
install -m 755 "$work/authkeys" "$KEYS_CMD"
chown root:root "$KEYS_CMD"

cat > "$work/sshd.conf" <<CONF
# MIA first contact (ADR-0025): any ed25519/ECDSA key may connect; the only thing it can run is the forced command,
# and that refuses everything without a valid server-signed grant. Every line below sits inside the Match block.
Match User $ENROLL_USER
    AuthorizedKeysFile none
    AuthorizedKeysCommand $KEYS_CMD %t %k
    AuthorizedKeysCommandUser nobody
    PubkeyAcceptedAlgorithms ssh-ed25519,ecdsa-sha2-nistp256,ecdsa-sha2-nistp384,ecdsa-sha2-nistp521
    ForceCommand /usr/bin/sudo $TOOL
    PermitUserRC no
    PasswordAuthentication no
    KbdInteractiveAuthentication no
    PermitTTY no
    AllowTcpForwarding no
    X11Forwarding no
    AllowAgentForwarding no
CONF
mkdir -p "$(dirname "$SSHD_DROPIN")"
install -m 644 "$work/sshd.conf" "$SSHD_DROPIN"
if command -v sshd >/dev/null 2>&1; then sshd -t; fi

echo "Done. Reload sshd (systemctl reload ssh). A phone can now enroll with: ssh mia-enroll@<pi> < request.json"
