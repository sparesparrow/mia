#!/usr/bin/env python3
"""Write a header with only the enums of schemas/voice.fbs, for firmware that cannot use FlatBuffers.

    python tools/schemas/extract_enums.py            # (re)write schemas/generated/cpp/voice_enums.h
    python tools/schemas/extract_enums.py --check    # exit 1 if the committed header is out of date

An ESP32 that only needs to know "which LED colour and which tone" includes this header and nothing
else. The names and numbers come from the schema, so they cannot drift from the wire format; a test
and CI run ``--check``.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path
from typing import List, Tuple

REPO_ROOT = Path(__file__).resolve().parents[2]
SCHEMA = REPO_ROOT / "schemas" / "voice.fbs"
HEADER = REPO_ROOT / "schemas" / "generated" / "cpp" / "voice_enums.h"

_ENUM = re.compile(r"enum\s+(\w+)\s*:\s*(\w+)\s*\{(.*?)\}", re.DOTALL)
_MEMBER = re.compile(r"(\w+)\s*=\s*(\d+)")
_CPP_TYPES = {
    "ubyte": "uint8_t",
    "byte": "int8_t",
    "ushort": "uint16_t",
    "short": "int16_t",
}

Enum = Tuple[str, str, List[Tuple[str, int]]]


def parse_enums(schema_text: str) -> List[Enum]:
    without_comments = re.sub(r"//[^\n]*", "", schema_text)
    enums: List[Enum] = []
    for name, base, body in _ENUM.findall(without_comments):
        if base not in _CPP_TYPES:
            raise ValueError(f"enum {name}: unsupported base type {base}")
        members = [(m, int(v)) for m, v in _MEMBER.findall(body)]
        if not members:
            raise ValueError(f"enum {name}: no members found")
        enums.append((name, _CPP_TYPES[base], members))
    return enums


def render(enums: List[Enum]) -> str:
    lines = [
        "// Generated by tools/schemas/extract_enums.py from schemas/voice.fbs. Do not edit.",
        "// Enums only, no FlatBuffers dependency, for microcontroller firmware.",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        "namespace MiaVoice {",
        "",
    ]
    for name, cpp_type, members in enums:
        lines.append(f"enum class {name} : {cpp_type} {{")
        lines.extend(f"  {member} = {value}," for member, value in members)
        lines.append("};")
        lines.append("")
    lines.append("}  // namespace MiaVoice")
    lines.append("")
    return "\n".join(lines)


def build() -> str:
    return render(parse_enums(SCHEMA.read_text(encoding="utf-8")))


def main(argv: List[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument(
        "--check", action="store_true", help="do not write; fail if the header is stale"
    )
    args = parser.parse_args(argv)

    expected = build()
    if args.check:
        current = HEADER.read_text(encoding="utf-8") if HEADER.exists() else ""
        if current != expected:
            print(
                f"{HEADER.relative_to(REPO_ROOT)} is out of date; run tools/schemas/extract_enums.py"
            )
            return 1
        print("voice_enums.h is up to date")
        return 0
    HEADER.write_text(expected, encoding="utf-8")
    print(f"wrote {HEADER.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
