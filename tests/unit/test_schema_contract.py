"""
Schema contract and binding staleness checks.

P1.2 — validates that FlatBuffers-generated Mia/ bindings are consistent
with the source schema in schemas/mia.fbs, and that Python consumers can
import all expected types without error.
"""

from __future__ import annotations

import importlib
import re
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parent.parent.parent

SCHEMA_DIR = REPO_ROOT / "schemas"
MIA_BINDINGS_DIR = REPO_ROOT / "Mia"

# Expected generated binding modules (one per FlatBuffers table/enum)
EXPECTED_BINDING_MODULES = [
    "Mia.GPIOCommand",
    "Mia.GPIODirection",
    "Mia.GPIOResponse",
    "Mia.SensorTelemetry",
    "Mia.SensorType",
    "Mia.SystemStatus",
    "Mia.CommandAck",
    "Mia.CommandStatus",
    "Mia.DeviceInfo",
    "Mia.DeviceType",
    "Mia.LEDState",
    "Mia.LEDMode",
    "Mia.AIState",
    "Mia.VehicleTelemetry",
]

AUTOGEN_HEADER = "automatically generated by the FlatBuffers compiler"


@pytest.mark.unit
class TestBindingModulesExist:
    """All expected FlatBuffers binding modules must be importable."""

    @pytest.mark.parametrize("module_name", EXPECTED_BINDING_MODULES)
    def test_binding_importable(self, module_name: str):
        mod = importlib.import_module(module_name)
        assert mod is not None

    def test_mia_package_importable(self):
        import Mia  # noqa: F401


@pytest.mark.unit
class TestBindingHeaders:
    """Generated bindings must carry the FlatBuffers auto-generation header."""

    def _binding_py_files(self):
        return sorted(MIA_BINDINGS_DIR.glob("*.py"))

    def test_binding_directory_exists(self):
        assert MIA_BINDINGS_DIR.is_dir(), f"Mia/ bindings directory missing at {MIA_BINDINGS_DIR}"

    def test_all_bindings_have_autogen_header(self):
        missing_header = []
        for py_file in self._binding_py_files():
            if py_file.name == "__init__.py":
                continue
            if py_file.name == "vehicle_codec.py":
                continue
            content = py_file.read_text(encoding="utf-8", errors="replace")
            if AUTOGEN_HEADER not in content:
                missing_header.append(py_file.name)
        assert not missing_header, (
            f"These Mia/ files lack the FlatBuffers auto-generated header "
            f"and may have been hand-edited: {missing_header}"
        )


