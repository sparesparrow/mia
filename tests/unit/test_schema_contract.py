@pytest.mark.unit
class TestSchemaTablesMatchBindings:
    """Tables declared in the FlatBuffers schema should have matching bindings."""

    def _extract_table_and_enum_names(self, fbs_path: Path) -> set[str]:
        content = fbs_path.read_text(encoding="utf-8")
        pattern = re.compile(r"(?:table|enum|struct)\s+(\w+)")
        return set(pattern.findall(content))

    def test_main_schema_types_have_bindings(self):
        schema_types = self._extract_table_and_enum_names(SCHEMA_DIR / "mia.fbs")
        binding_files = {p.stem for p in MIA_BINDINGS_DIR.glob("*.py")} - {"__init__", "vehicle_codec"}

        missing = schema_types - binding_files
        assert not missing, (
            f"Schema defines types {missing} but no matching Mia/*.py binding exists. "
            f"Run 'python schemas/generate.py' to regenerate."
        )


@pytest.mark.unit
class TestNormalizedPayloadContract:
    """The normalized telemetry payload must include all generic PID fields."""

    def test_generic_pid_fields_present(self):
        from apps.rpi_backend.shared.telemetry import normalized_payload as _np

        # handle import path differences
        try:
            fields = _np.GENERIC_PID_FIELDS
        except AttributeError:
            pytest.skip("normalized_payload module not available via this import path")

        expected = {"speed_kmh", "engine_rpm", "coolant_temp_c", "fuel_level_percent", "battery_voltage", "vin"}
        assert expected.issubset(fields), f"Missing generic PID fields: {expected - fields}"

    def test_valid_capability_classes(self):
        from apps.rpi_backend.shared.telemetry import normalized_payload as _np

        try:
            classes = _np.VALID_CAPABILITY_CLASSES
        except AttributeError:
            pytest.skip("normalized_payload module not available via this import path")

        assert "unknown" in classes
        assert "generic_pid_only" in classes
        assert "uds_read_only" in classes

    def test_build_payload_includes_timestamp(self):
        from apps.rpi_backend.shared.telemetry import normalized_payload as _np

        try:
            payload = _np.build_telemetry_payload(speed_kmh=60)
        except (AttributeError, TypeError):
            pytest.skip("build_telemetry_payload not available")

        assert "timestamp" in payload
        assert "speed_kmh" in payload
