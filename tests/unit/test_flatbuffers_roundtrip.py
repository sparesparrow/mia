# --------------------------------------------------------------------------- #
# CommandAck — strings + enum + byte vector
# --------------------------------------------------------------------------- #

class TestCommandAckRoundtrip:
    def test_roundtrip_without_vector(self):
        builder = flatbuffers.Builder(128)
        cmd_id = builder.CreateString("cmd-abc")
        err = builder.CreateString("")

        CommandAck.Start(builder)
        CommandAck.AddCommandId(builder, cmd_id)
        CommandAck.AddStatus(builder, CommandStatus.CommandStatus.Success)
        CommandAck.AddErrorMessage(builder, err)
        CommandAck.AddTimestamp(builder, 42)
        end = CommandAck.End(builder)
        builder.Finish(end)

        parsed = CommandAck.CommandAck.GetRootAs(builder.Output(), 0)
        assert parsed.CommandId() == b"cmd-abc"
        assert parsed.Status() == CommandStatus.CommandStatus.Success
        assert parsed.ErrorMessage() == b""
        assert parsed.Timestamp() == 42

    def test_roundtrip_with_response_data(self):
        builder = flatbuffers.Builder(128)

        # Build the byte vector first (flatbuffers requires reverse order of nesting).
        payload = bytes([1, 2, 3, 4, 5])
        CommandAck.StartResponseDataVector(builder, len(payload))
        for b in reversed(payload):
            builder.PrependByte(b)
        response_vec = builder.EndVector()

        cmd_id = builder.CreateString("cmd-xyz")
        err = builder.CreateString("oops")

        CommandAck.Start(builder)
        CommandAck.AddCommandId(builder, cmd_id)
        CommandAck.AddStatus(builder, CommandStatus.CommandStatus.Failure)
        CommandAck.AddErrorMessage(builder, err)
        CommandAck.AddResponseData(builder, response_vec)
        CommandAck.AddTimestamp(builder, 100)
        end = CommandAck.End(builder)
        builder.Finish(end)

        parsed = CommandAck.CommandAck.GetRootAs(builder.Output(), 0)
        assert parsed.CommandId() == b"cmd-xyz"
        assert parsed.Status() == CommandStatus.CommandStatus.Failure
        assert parsed.ErrorMessage() == b"oops"
        assert parsed.ResponseDataLength() == 5
        assert [parsed.ResponseData(i) for i in range(5)] == list(payload)
        assert parsed.Timestamp() == 100


# --------------------------------------------------------------------------- #
# DeviceInfo — string vector of capabilities
# --------------------------------------------------------------------------- #

class TestDeviceInfoRoundtrip:
    def test_roundtrip_with_capabilities(self):
        builder = flatbuffers.Builder(256)

        cap_1 = builder.CreateString("read")
        cap_2 = builder.CreateString("write")
        DeviceInfo.StartCapabilitiesVector(builder, 2)
        builder.PrependUOffsetTRelative(cap_2)
        builder.PrependUOffsetTRelative(cap_1)
        caps_vec = builder.EndVector()

        device_id = builder.CreateString("gpio-17")
        name = builder.CreateString("Kitchen Light")
        status = builder.CreateString("online")

        DeviceInfo.Start(builder)
        DeviceInfo.AddDeviceId(builder, device_id)
        DeviceInfo.AddDeviceType(builder, DeviceType.DeviceType.GPIO)
        DeviceInfo.AddName(builder, name)
        DeviceInfo.AddCapabilities(builder, caps_vec)
        DeviceInfo.AddStatus(builder, status)
        DeviceInfo.AddLastSeen(builder, 999)
        end = DeviceInfo.End(builder)
        builder.Finish(end)

        parsed = DeviceInfo.DeviceInfo.GetRootAs(builder.Output(), 0)
        assert parsed.DeviceId() == b"gpio-17"
        assert parsed.DeviceType() == DeviceType.DeviceType.GPIO
        assert parsed.Name() == b"Kitchen Light"
        assert parsed.Status() == b"online"
        assert parsed.LastSeen() == 999
        assert parsed.CapabilitiesLength() == 2
        assert parsed.Capabilities(0) == b"read"
        assert parsed.Capabilities(1) == b"write"


