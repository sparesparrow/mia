# --------------------------------------------------------------------------- #
# GPIOCommand — all scalar fields
# --------------------------------------------------------------------------- #

class TestGPIOCommandRoundtrip:
    def test_roundtrip_all_fields(self):
        builder = flatbuffers.Builder(128)
        GPIOCommand.Start(builder)
        GPIOCommand.AddPin(builder, 17)
        GPIOCommand.AddDirection(builder, GPIODirection.GPIODirection.Output)
        GPIOCommand.AddValue(builder, True)
        GPIOCommand.AddTimestamp(builder, 1_700_000_000_000)
        end = GPIOCommand.End(builder)
        builder.Finish(end)

        parsed = GPIOCommand.GPIOCommand.GetRootAs(builder.Output(), 0)
        assert parsed.Pin() == 17
        assert parsed.Direction() == GPIODirection.GPIODirection.Output
        assert parsed.Value() is True
        assert parsed.Timestamp() == 1_700_000_000_000

    def test_defaults_when_unset(self):
        builder = flatbuffers.Builder(128)
        GPIOCommand.Start(builder)
        end = GPIOCommand.End(builder)
        builder.Finish(end)

        parsed = GPIOCommand.GPIOCommand.GetRootAs(builder.Output(), 0)
        assert parsed.Pin() == 0
        assert parsed.Value() is False
        assert parsed.Timestamp() == 0


